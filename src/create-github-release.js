// Creates the GitHub release for the vX.Y.Z tag, or updates it when it already exists. Run by JenkinsfileRelease
// after the package is published to npm.
//
// The release notes contain:
//   - links to the npm package and to the version's tokens browser and CSS variables diff on GitHub Pages
//   - the design token changes: the messages of the token sync commits (the ones with Gw-Theme-Commit trailers)
//     since the previous release
//   - the CSS variables summary from `npm run compare-css-variables` (generated/css-variables-diff.md), which must
//     be run for the same version before this script
//   - the pull requests merged since the previous release (generated by GitHub)
//
// Usage:
//   GITHUB_TOKEN=<token> node src/create-github-release.js --version X.Y.Z
//   GITHUB_TOKEN=<token> node src/create-github-release.js --version X.Y.Z --dry-run
//       write the notes to generated/release-notes.md instead of creating the release
import fs from 'fs';
import path from 'path';

const REPOSITORY = 'Ontotext-AD/graphwise-styleguide';
const PACKAGE_NAME = 'graphwise-styleguide';
const PAGES_URL = 'https://ontotext-ad.github.io/graphwise-styleguide';
const CSS_DIFF_FILE = 'generated/css-variables-diff.md';
const TRAILER = 'Gw-Theme-Commit';
// Must match the marker in src/compare-css-variables.js, the full lists of added and changed variables follow it.
const DETAILS_MARKER = '<!-- details -->';
// GitHub rejects release bodies longer than 125000 characters.
const MAX_BODY_LENGTH = 120000;
const STABLE_VERSION_PATTERN = /^\d+\.\d+\.\d+$/;

function getArg(name) {
  const index = process.argv.indexOf(`--${name}`);
  return index !== -1 ? process.argv[index + 1] : undefined;
}

function fail(message) {
  console.error(`❌ ${message}`);
  process.exit(1);
}

const version = getArg('version');
const isDryRun = process.argv.includes('--dry-run');
const token = process.env.GITHUB_TOKEN;
if (!version || !STABLE_VERSION_PATTERN.test(version)) {
  fail(`Pass the released version with --version X.Y.Z, got: ${JSON.stringify(version)}`);
}
if (!token) {
  fail('The GITHUB_TOKEN environment variable is not set.');
}
if (!fs.existsSync(CSS_DIFF_FILE)) {
  fail(`Missing ${CSS_DIFF_FILE}. Run "npm run compare-css-variables -- --before ${version}" first.`);
}
const tag = `v${version}`;

async function github(method, endpoint, body) {
  const response = await fetch(`https://api.github.com/repos/${REPOSITORY}${endpoint}`, {
    method,
    headers: {
      Accept: 'application/vnd.github+json',
      Authorization: `Bearer ${token}`,
      'X-GitHub-Api-Version': '2022-11-28',
    },
    body: body && JSON.stringify(body),
  });
  if (response.status === 404 && method === 'GET') {
    return undefined;
  }
  if (!response.ok) {
    fail(`GitHub API ${method} ${endpoint} failed with ${response.status}: ${await response.text()}`);
  }
  return response.json();
}

function compareVersions(a, b) {
  const pa = a.split('.').map(Number);
  const pb = b.split('.').map(Number);
  for (let i = 0; i < 3; i++) {
    if (pa[i] !== pb[i]) return pa[i] - pb[i];
  }
  return 0;
}

// The latest vX.Y.Z tag before the released version: the start of the commit and pull request lists.
async function findPreviousTag() {
  const refs = (await github('GET', '/git/matching-refs/tags/v')) || [];
  const previous = refs
    .map((ref) => ref.ref.replace('refs/tags/v', ''))
    .filter((v) => STABLE_VERSION_PATTERN.test(v) && compareVersions(v, version) < 0)
    .sort(compareVersions)
    .pop();
  return previous && `v${previous}`;
}

// The message of a token sync commit without its trailers (e.g. "Gw-Theme-Commit: ...", "Co-authored-by: ...")
// and the "---------" separator GitHub adds to squash messages.
function tokenChanges(message) {
  const [title, ...body] = message.split('\n');
  const lines = body.filter(
    (line) => !new RegExp(`^(${TRAILER}|Co-authored-by|Signed-off-by): `, 'i').test(line) && !/^-{3,}$/.test(line.trim())
  );
  const text = lines.join('\n').replace(/\n{3,}/g, '\n\n').trim();
  return `#### ${title}\n\n${text || '_No description._'}`;
}

async function designTokenSection(previousTag) {
  if (!previousTag) {
    return undefined;
  }
  const comparison = await github('GET', `/compare/${previousTag}...${tag}?per_page=250`);
  const syncs = comparison.commits
    .map((commit) => commit.commit.message)
    .filter((message) => new RegExp(`^${TRAILER}: [0-9a-f]{40}$`, 'm').test(message))
    .reverse();
  return syncs.length ? `## Design token changes\n\n${syncs.map(tokenChanges).join('\n\n')}` : undefined;
}

function cssVariablesSection(full) {
  const summary = fs.readFileSync(CSS_DIFF_FILE, 'utf8').trim();
  const content = full
    ? summary.replace(DETAILS_MARKER, '').trim()
    : `${summary.split(DETAILS_MARKER)[0].trim()}\n\nThe lists of added and changed variables are in the CSS variables diff.`;
  return `## CSS variables\n\n${content}`;
}

const previousTag = await findPreviousTag();
console.info(`🔖 Previous release: ${previousTag || 'none'}`);

const links = [
  `**npm:** [${PACKAGE_NAME}@${version}](https://www.npmjs.com/package/${PACKAGE_NAME}/v/${version})`,
  `**Tokens browser:** ${PAGES_URL}/${tag}/tokens-browser.html`,
  `**CSS variables diff:** ${PAGES_URL}/${tag}/css-variables-diff.html`,
].join('<br>\n');
const designTokens = await designTokenSection(previousTag);
const { body: pullRequests } = await github('POST', '/releases/generate-notes', {
  tag_name: tag,
  ...(previousTag && { previous_tag_name: previousTag }),
});

const compose = (fullCssVariables) =>
  [links, designTokens, cssVariablesSection(fullCssVariables), pullRequests].filter(Boolean).join('\n\n');
let body = compose(true);
if (body.length > MAX_BODY_LENGTH) {
  console.info('ℹ️  The release notes are too long, leaving out the lists of added and changed CSS variables.');
  body = compose(false);
}

if (isDryRun) {
  const notesFile = path.join('generated', 'release-notes.md');
  fs.writeFileSync(notesFile, body);
  console.info(`✅ Release notes written to ${notesFile}`);
  process.exit(0);
}

const release = { tag_name: tag, name: tag, body };
const existing = await github('GET', `/releases/tags/${tag}`);
const result = existing
  ? await github('PATCH', `/releases/${existing.id}`, release)
  : await github('POST', '/releases', release);
console.info(`✅ ${existing ? 'Updated' : 'Created'} release ${tag}: ${result.html_url}`);
fs.writeFileSync(path.join('generated', 'release-url.txt'), result.html_url);
